"""Users, passwords, login throttling and audit log (PostgreSQL).

Passwords are hashed with Werkzeug (scrypt/PBKDF2, salted). Accounts lock for
LOCK_MINUTES after MAX_FAILED_ATTEMPTS consecutive failed logins.

The first administrator is created either from the command line

    python -m paycheck_sentinel.auth create-admin

or, at the first start with an empty user table, from the environment variables
INITIAL_ADMIN_USER (default "admin") and INITIAL_ADMIN_PASSWORD.

Other commands: reset-password USERNAME (also unlocks the account) and list-users.
"""

import argparse
import getpass
import logging
import os
import re
import sys

import psycopg
from werkzeug.security import check_password_hash, generate_password_hash

from . import db

log = logging.getLogger(__name__)

ROLES = ("admin", "user")
MIN_PASSWORD_LENGTH = 10
MAX_PASSWORD_LENGTH = 128
MAX_FAILED_ATTEMPTS = 5
LOCK_MINUTES = 15
USERNAME_RE = re.compile(r"^[a-z0-9._-]{3,32}$")

# Advisory lock that serializes changes to administrators (db.py uses 727001,
# licensing.py 727002).
AUTH_LOCK_ID = 727003

# Checked for unknown/locked/inactive accounts, so that a failed login takes about the
# same time whether or not the username exists.
_DUMMY_HASH = generate_password_hash("not-a-real-password")

SCHEMA = """
CREATE TABLE IF NOT EXISTS app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('admin', 'user')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
    failed_attempts INTEGER NOT NULL DEFAULT 0,
    locked_until TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_login_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS app_audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at TIMESTAMPTZ NOT NULL DEFAULT now(),
    username TEXT NOT NULL DEFAULT '',
    action TEXT NOT NULL,
    detail TEXT NOT NULL DEFAULT '',
    ip TEXT NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS idx_app_audit_log_at ON app_audit_log(at);
"""

_PUBLIC_COLUMNS = ("id", "username", "role", "is_active", "must_change_password",
                   "created_at", "last_login_at")


def _public(row):
    """User row without the password hash; timestamps as ISO strings."""
    if not row:
        return None
    user = {k: row[k] for k in _PUBLIC_COLUMNS}
    for key in ("created_at", "last_login_at"):
        user[key] = user[key].isoformat(timespec="seconds") if user[key] else None
    return user


def normalize_username(value):
    """Lower-case, trimmed username, or '' if it does not look like a valid one."""
    name = str(value or "").strip().lower()
    return name if USERNAME_RE.match(name) else ""


def validate_password(password, username=""):
    if not isinstance(password, str):
        raise ValueError("Password is required.")
    if len(password) < MIN_PASSWORD_LENGTH:
        raise ValueError(f"Password must have at least {MIN_PASSWORD_LENGTH} characters.")
    if len(password) > MAX_PASSWORD_LENGTH:
        raise ValueError(f"Password must have at most {MAX_PASSWORD_LENGTH} characters.")
    if username and password.strip().lower() == username.lower():
        raise ValueError("Password must not be the same as the username.")


def init_auth_schema():
    """Create the tables and, if there are no users yet, bootstrap the first admin."""
    with db.get_db() as conn:
        conn.execute("SELECT pg_advisory_xact_lock(%s)", (db.SCHEMA_LOCK_ID,))
        conn.execute(SCHEMA)

    if count_users() == 0:
        password = os.environ.get("INITIAL_ADMIN_PASSWORD", "")
        if password:
            username = normalize_username(os.environ.get("INITIAL_ADMIN_USER", "admin")) or "admin"
            try:
                create_user(username, password, "admin", must_change_password=True)
                log.warning("Created the initial administrator %r from the environment; "
                            "a password change is required at the first login.", username)
            except ValueError as exc:
                log.error("INITIAL_ADMIN_PASSWORD was not used: %s", exc)


def count_users():
    with db.get_db() as conn:
        return conn.execute("SELECT count(*) AS n FROM app_users").fetchone()["n"]


def get_user(user_id):
    with db.get_db() as conn:
        return _public(conn.execute("SELECT * FROM app_users WHERE id = %s", (user_id,)).fetchone())


def list_users():
    with db.get_db() as conn:
        rows = conn.execute("SELECT * FROM app_users ORDER BY username").fetchall()
    return [_public(r) for r in rows]


def create_user(username, password, role="user", must_change_password=True):
    name = normalize_username(username)
    if not name:
        raise ValueError("Username must have 3-32 characters: letters, digits, '.', '_' or '-'.")
    if role not in ROLES:
        raise ValueError("Role must be 'admin' or 'user'.")
    validate_password(password, name)

    try:
        with db.get_db() as conn:
            row = conn.execute(
                """INSERT INTO app_users (username, password_hash, role, must_change_password)
                   VALUES (%s, %s, %s, %s) RETURNING *""",
                (name, generate_password_hash(password), role, bool(must_change_password)),
            ).fetchone()
    except psycopg.errors.UniqueViolation:
        raise ValueError("A user with that username already exists.")
    return _public(row)


def authenticate(username, password):
    """Check credentials, applying the lockout rules.

    Returns (user, reason). reason is "ok" on success, otherwise one of "unknown_user",
    "locked", "inactive" or "bad_password" (for the audit log only: callers must show
    the same generic message for all of them).
    """
    name = normalize_username(username)
    password = password if isinstance(password, str) else ""
    if len(password) > MAX_PASSWORD_LENGTH:
        password = password[:MAX_PASSWORD_LENGTH]

    with db.get_db() as conn:
        row = conn.execute(
            """SELECT *, (locked_until IS NOT NULL AND locked_until > now()) AS is_locked
               FROM app_users WHERE username = %s""",
            (name,),
        ).fetchone() if name else None

        if row is None:
            check_password_hash(_DUMMY_HASH, password)
            return None, "unknown_user"
        if row["is_locked"] or not row["is_active"]:
            check_password_hash(_DUMMY_HASH, password)
            return None, "locked" if row["is_locked"] else "inactive"

        if check_password_hash(row["password_hash"], password):
            row = conn.execute(
                """UPDATE app_users SET failed_attempts = 0, locked_until = NULL,
                          last_login_at = now() WHERE id = %s RETURNING *""",
                (row["id"],),
            ).fetchone()
            return _public(row), "ok"

        conn.execute(
            """UPDATE app_users SET
                 failed_attempts = CASE WHEN failed_attempts + 1 >= %s THEN 0 ELSE failed_attempts + 1 END,
                 locked_until = CASE WHEN failed_attempts + 1 >= %s
                                     THEN now() + make_interval(mins => %s::int) ELSE locked_until END
               WHERE id = %s""",
            (MAX_FAILED_ATTEMPTS, MAX_FAILED_ATTEMPTS, LOCK_MINUTES, row["id"]),
        )
        return None, "bad_password"


def set_password(user_id, new_password, must_change_password=False):
    """Set a new password and clear any lockout."""
    user = get_user(user_id)
    if not user:
        raise ValueError("User not found.")
    validate_password(new_password, user["username"])
    with db.get_db() as conn:
        conn.execute(
            """UPDATE app_users SET password_hash = %s, must_change_password = %s,
                      failed_attempts = 0, locked_until = NULL WHERE id = %s""",
            (generate_password_hash(new_password), bool(must_change_password), user_id),
        )


def update_user(user_id, role=None, is_active=None):
    """Change role and/or active flag; the last active administrator cannot be removed."""
    if role is not None and role not in ROLES:
        raise ValueError("Role must be 'admin' or 'user'.")

    with db.get_db() as conn:
        conn.execute("SELECT pg_advisory_xact_lock(%s)", (AUTH_LOCK_ID,))
        row = conn.execute("SELECT * FROM app_users WHERE id = %s", (user_id,)).fetchone()
        if not row:
            raise ValueError("User not found.")

        new_role = row["role"] if role is None else role
        new_active = row["is_active"] if is_active is None else bool(is_active)

        was_active_admin = row["role"] == "admin" and row["is_active"]
        stays_active_admin = new_role == "admin" and new_active
        if was_active_admin and not stays_active_admin:
            others = conn.execute(
                "SELECT count(*) AS n FROM app_users WHERE role = 'admin' AND is_active AND id <> %s",
                (user_id,),
            ).fetchone()["n"]
            if others == 0:
                raise ValueError("At least one active administrator is required.")

        row = conn.execute(
            "UPDATE app_users SET role = %s, is_active = %s WHERE id = %s RETURNING *",
            (new_role, new_active, user_id),
        ).fetchone()
    return _public(row)


def audit(username, action, detail="", ip=""):
    """Write an audit log entry. Never raises: auditing must not break a request."""
    try:
        with db.get_db() as conn:
            conn.execute(
                "INSERT INTO app_audit_log (username, action, detail, ip) VALUES (%s, %s, %s, %s)",
                (username or "", action, str(detail or "")[:500], ip or ""),
            )
    except Exception:
        log.exception("Could not write the audit log entry %r", action)


def recent_audit(limit=100):
    with db.get_db() as conn:
        rows = conn.execute(
            "SELECT at, username, action, detail, ip FROM app_audit_log ORDER BY id DESC LIMIT %s",
            (max(1, min(int(limit), 500)),),
        ).fetchall()
    return [{**r, "at": r["at"].isoformat(timespec="seconds")} for r in rows]


# ---------------------------------------------------------------- command line

def _ask_password(label="Password"):
    while True:
        first = getpass.getpass(f"{label}: ")
        if first != getpass.getpass("Repeat the password: "):
            print("The passwords do not match, try again.", file=sys.stderr)
            continue
        return first


def main(argv=None):
    parser = argparse.ArgumentParser(prog="python -m paycheck_sentinel.auth",
                                     description="Manage Paycheck Sentinel users.")
    sub = parser.add_subparsers(dest="command", required=True)

    create = sub.add_parser("create-admin", help="create an administrator account")
    create.add_argument("--username", default="admin")

    reset = sub.add_parser("reset-password", help="set a new password and unlock the account")
    reset.add_argument("username")

    sub.add_parser("list-users", help="list all users")

    args = parser.parse_args(argv)
    db.init_db()
    init_auth_schema()

    try:
        if args.command == "create-admin":
            user = create_user(args.username, _ask_password(), "admin", must_change_password=False)
            audit("cli", "user_created", f"{user['username']} (admin)")
            print(f"Administrator '{user['username']}' created.")
        elif args.command == "reset-password":
            user = next((u for u in list_users() if u["username"] == normalize_username(args.username)), None)
            if not user:
                raise ValueError("User not found.")
            set_password(user["id"], _ask_password("New password"), must_change_password=True)
            audit("cli", "password_reset", user["username"])
            print(f"Password for '{user['username']}' changed; it must be changed again at the next login.")
        else:
            for u in list_users():
                state = "active" if u["is_active"] else "disabled"
                print(f"{u['username']:<20} {u['role']:<6} {state:<9} last login: {u['last_login_at'] or '-'}")
    except ValueError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())