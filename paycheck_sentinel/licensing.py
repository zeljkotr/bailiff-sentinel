"""Offline Ed25519 license validation and the free-mode upload quota (PostgreSQL).

Without a commercial license the application runs in free mode: at most
FREE_DOCS_PER_WINDOW XML documents can be uploaded in any rolling
FREE_WINDOW_HOURS-hour window. Uploads are logged in PostgreSQL, so the limit is
shared by all workers and instances. A valid commercial license removes the limit.
"""

import base64
import binascii
import json
import math
import os
import uuid
from datetime import date

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey

from . import db


FREE_DOCS_PER_WINDOW = 3
FREE_WINDOW_HOURS = 24
LICENSE_ENV = "PAYCHECK_SENTINEL_LICENSE"

# Advisory lock key that serializes quota checks across workers/instances
# (db.py uses 727001 for the schema).
QUOTA_LOCK_ID = 727002
LOG_RETENTION_DAYS = 7

# Public key only. The corresponding private key stays in license-tools.
PUBLIC_KEY_B64 = "WRSBNr2KDA5m/Ly255aZMENHFoBPpw4in83tCc6lCXY="


def _decode_urlsafe(value):
    if not isinstance(value, str) or not value:
        raise ValueError("Missing encoded value")
    raw = value.encode("ascii")
    raw += b"=" * (-len(raw) % 4)
    return base64.b64decode(raw, altchars=b"-_", validate=True)


def verify_license(token, public_key_b64=PUBLIC_KEY_B64, today=None):
    """Return a validation result without raising for malformed license data."""
    today = today or date.today()

    try:
        parts = token.split(".")
        if len(parts) != 3 or parts[0] != "PS1":
            raise ValueError("Invalid license format")

        payload_bytes = _decode_urlsafe(parts[1])
        signature = _decode_urlsafe(parts[2])
        public_key_bytes = base64.b64decode(public_key_b64, validate=True)

        if len(public_key_bytes) != 32:
            raise ValueError("Invalid public key")

        public_key = Ed25519PublicKey.from_public_bytes(public_key_bytes)
        public_key.verify(signature, payload_bytes)

        payload = json.loads(payload_bytes.decode("utf-8"))
        if not isinstance(payload, dict) or payload.get("v") != 1:
            raise ValueError("Unsupported license version")

        license_id = payload.get("id")
        uuid.UUID(str(license_id))

        licensee = payload.get("licensee")
        if not isinstance(licensee, str) or not licensee.strip():
            raise ValueError("Missing licensee")

        issued = date.fromisoformat(payload["issued"])
        expires_raw = payload.get("expires")
        expires = date.fromisoformat(expires_raw) if expires_raw is not None else None

        if issued > today:
            raise ValueError("License issue date is in the future")
        if expires is not None and expires < today:
            raise ValueError("License has expired")

        return {
            "valid": True,
            "license_id": str(license_id),
            "licensee": licensee.strip(),
            "expires": expires.isoformat() if expires else None,
            "reason": None,
        }

    except (ValueError, TypeError, KeyError, UnicodeError, binascii.Error,
            InvalidSignature, json.JSONDecodeError) as exc:
        return {"valid": False, "reason": str(exc) or "Invalid license"}
    except Exception:
        return {"valid": False, "reason": "Invalid license"}


def save_license_token(token):
    """Verify and persist a commercial license token in PostgreSQL."""
    result = verify_license(token)
    if not result["valid"]:
        raise ValueError(result["reason"] or "Invalid license")

    with db.get_db() as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS app_license_key (
                singleton_id SMALLINT PRIMARY KEY CHECK (singleton_id = 1),
                license_token TEXT NOT NULL
            )
        """)
        conn.execute("""
            INSERT INTO app_license_key (singleton_id, license_token)
            VALUES (1, %s)
            ON CONFLICT (singleton_id)
            DO UPDATE SET license_token = EXCLUDED.license_token
        """, (token.strip(),))

    return result


def initialize_license_state():
    """Create the license and upload-log tables (safe to call from every worker)."""
    with db.get_db() as conn:
        # Same advisory lock as the schema creation in db.init_db(), so workers that
        # start at the same time do not race on CREATE TABLE.
        conn.execute("SELECT pg_advisory_xact_lock(%s)", (db.SCHEMA_LOCK_ID,))
        conn.execute("""
            CREATE TABLE IF NOT EXISTS app_license_key (
                singleton_id SMALLINT PRIMARY KEY CHECK (singleton_id = 1),
                license_token TEXT NOT NULL
            )
        """)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS app_upload_log (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                uploaded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                file_name TEXT NOT NULL DEFAULT ''
            )
        """)
        conn.execute(
            "CREATE INDEX IF NOT EXISTS idx_app_upload_log_time ON app_upload_log(uploaded_at)"
        )


def format_wait(seconds):
    """3725 -> '1 h 2 min' (rounded up to whole minutes)."""
    minutes = max(1, math.ceil(float(seconds) / 60))
    hours, minutes = divmod(minutes, 60)
    if hours and minutes:
        return f"{hours} h {minutes} min"
    if hours:
        return f"{hours} h"
    return f"{minutes} min"


def _stored_token(conn):
    row = conn.execute(
        "SELECT license_token FROM app_license_key WHERE singleton_id = 1"
    ).fetchone()
    return ((row["license_token"] if row else "") or
            os.environ.get(LICENSE_ENV, "")).strip()


def _window_usage(conn):
    """Return (used, seconds_until_next_slot) for the rolling window.

    seconds_until_next_slot is 0 while at least one slot is free. When the quota is
    used up, it is the time until enough old uploads leave the window for one slot to
    open (the (used - limit + 1)-th oldest upload has to expire).
    """
    rows = conn.execute(
        """
        SELECT EXTRACT(EPOCH FROM (uploaded_at + make_interval(hours => %s::int) - now())) AS seconds_left
        FROM app_upload_log
        WHERE uploaded_at > now() - make_interval(hours => %s::int)
        ORDER BY uploaded_at
        """,
        (FREE_WINDOW_HOURS, FREE_WINDOW_HOURS),
    ).fetchall()

    used = len(rows)
    if used < FREE_DOCS_PER_WINDOW:
        return used, 0.0
    return used, max(0.0, float(rows[used - FREE_DOCS_PER_WINDOW]["seconds_left"]))


def _summary(status):
    if status["type"] == "commercial":
        return ""
    if status["remaining"] > 0:
        return (f"Free version: {status['remaining']} of {status['limit']} XML documents "
                f"left in the current {status['window_hours']} h window.")
    return (f"Free version: limit reached ({status['limit']} XML documents per "
            f"{status['window_hours']} h). Next upload possible in "
            f"{format_wait(status['retry_after_seconds'])}.")


def limit_message(status):
    """Error text for an upload that was refused because the free quota is used up."""
    return (f"Free version limit reached: {status['limit']} XML documents per "
            f"{status['window_hours']} hours. You can upload again in "
            f"{format_wait(status['retry_after_seconds'])}. "
            "Enter an activation key to remove the limit.")


def get_license_status(today=None):
    """Commercial license if a valid one is stored, otherwise free mode with quota info.

    The application is always usable ("active" is always True); what differs is the
    upload quota. If a stored license is invalid or expired, the application falls back
    to free mode and reports the reason in "license_error".
    """
    today = today or date.today()
    license_error = None

    with db.get_db() as conn:
        token = _stored_token(conn)
        if token:
            result = verify_license(token, today=today)
            if result["valid"]:
                status = {
                    "active": True,
                    "type": "commercial",
                    "licensee": result["licensee"],
                    "expires": result["expires"],
                    "reason": None,
                    "license_error": None,
                }
                status["summary"] = _summary(status)
                return status
            license_error = result["reason"]

        used, retry_after = _window_usage(conn)

    status = {
        "active": True,
        "type": "free",
        "limit": FREE_DOCS_PER_WINDOW,
        "window_hours": FREE_WINDOW_HOURS,
        "used": used,
        "remaining": max(0, FREE_DOCS_PER_WINDOW - used),
        "retry_after_seconds": int(math.ceil(retry_after)),
        "reason": license_error,
        "license_error": license_error,
    }
    status["summary"] = _summary(status)
    return status


def reserve_upload_slots(file_names, today=None):
    """Reserve free-mode slots for the given files and return how many were granted.

    With a valid commercial license every file is granted and nothing is logged. In
    free mode, at most the remaining slots of the rolling window are granted (the first
    files in the list win) and one log row is written per granted file. The check and
    the insert run in one transaction under an advisory lock, so concurrent uploads on
    different workers or instances cannot exceed the limit together.
    """
    names = list(file_names)
    if not names:
        return 0

    with db.get_db() as conn:  # commits on success and releases the advisory lock
        conn.execute("SELECT pg_advisory_xact_lock(%s)", (QUOTA_LOCK_ID,))

        token = _stored_token(conn)
        if token and verify_license(token, today=today)["valid"]:
            return len(names)

        conn.execute(
            "DELETE FROM app_upload_log WHERE uploaded_at < now() - make_interval(days => %s::int)",
            (LOG_RETENTION_DAYS,),
        )
        used, _ = _window_usage(conn)
        granted = min(max(0, FREE_DOCS_PER_WINDOW - used), len(names))
        for name in names[:granted]:
            conn.execute("INSERT INTO app_upload_log (file_name) VALUES (%s)", (name,))

    return granted